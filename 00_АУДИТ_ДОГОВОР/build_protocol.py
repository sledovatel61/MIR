def set_cell_border(cell, **kwargs):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcBorders = tcPr.find(qn('w:tcBorders'))
    if tcBorders is None:
        tcBorders = OxmlElement('w:tcBorders')
        tcPr.append(tcBorders)
    for edge in ('top', 'left', 'bottom', 'right'):
        if edge in kwargs:
            tag = OxmlElement(f'w:{edge}')
            tag.set(qn('w:val'), kwargs[edge].get('val', 'single'))
            tag.set(qn('w:sz'), str(kwargs[edge].get('sz', 4)))
            tag.set(qn('w:space'), '0')
            tag.set(qn('w:color'), kwargs[edge].get('color', '000000'))
            existing = tcBorders.find(qn(f'w:{edge}'))
            if existing is not None:
                tcBorders.remove(existing)
            tcBorders.append(tag)


def add_paragraph(doc, text, bold=False, size=11, align=None, space_after=6, indent_first=None):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    if indent_first is not None:
        p.paragraph_format.first_line_indent = Cm(indent_first)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.15
    run = p.add_run(text)
    run.font.name = 'Times New Roman'
    run.font.size = Pt(size)
    run.bold = bold
    return p


