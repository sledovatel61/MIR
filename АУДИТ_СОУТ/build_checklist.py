HEADER = ("№", "Где в документе", "Что заполнить",
          "Откуда взять (документ / источник)", "Готово (дата, инициалы)")

WIDTHS = [0.9, 3.4, 7.2, 4.7, 1.6]  # = 17.8 — скорректируется под usable


def build():
    from docx import Document
    from docx.shared import Cm, Pt

    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = TNR_FONT
    st.font.size = Pt(10)
    st.paragraph_format.space_after = Pt(0)
    st.paragraph_format.line_spacing = 1.15

    sec = doc.sections[0]
    set_page(sec, landscape=False, margin_lr=1.8, margin_tb=1.5)
    u = usable_width(sec)
    widths = [w / sum(WIDTHS) * u for w in WIDTHS]

    _par(doc, "ЧЕК-ЛИСТ ПЕРЕД ОТПРАВКОЙ", bold=True, size=13,
         align=WD_ALIGN_PARAGRAPH.CENTER, space_after=2)
    _par(doc, "ООО «МИР» — специальная оценка условий труда: что заполнить в Приложениях № 1–4 "
              "до подписания письма и откуда взять данные", size=10,
         align=WD_ALIGN_PARAGRAPH.CENTER, italic=True, space_after=8)
    _par(doc, "В Приложениях № 1–4 письма 35 пометок [до подписания] — это 9 групп ниже. "
              "Заполните эти поля и верните документ до подписания экземпляра. Все остальные "
              "справочные данные (инвентарные номера, год выпуска, модели и типы техники, "
              "наличие тахографа и ГЛОНАСС/GPS, регистрационные знаки Гостехнадзора, состав "
              "технических жидкостей, состав обвязочных материалов и пр.) комиссия СОУТ "
              "зафиксирует на месте при посещении рабочих мест — заполнять их в письме не "
              "нужно.", size=10, space_after=6)

    t = doc.add_table(rows=1, cols=len(HEADER))
    t.style = "Table Grid"
    t.autofit = False
    for j, h in enumerate(HEADER):
        c = t.rows[0].cells[j]
        write_cell(c, h, bold=True, size=9, align=WD_ALIGN_PARAGRAPH.CENTER)
        cell_shading(c, "D9D9D9")
    for num, where, what, src, done in ROWS:
        cells = t.add_row().cells
        write_cell(cells[0], num, size=9, align=WD_ALIGN_PARAGRAPH.CENTER)
        write_cell(cells[1], where, size=9)
        write_cell(cells[2], what, size=9)
        write_cell(cells[3], src, size=9)
        write_cell(cells[4], done, size=9, align=WD_ALIGN_PARAGRAPH.CENTER)
    for r in t.rows:
        for c in r.cells:
            cell_borders(c)
    apply_layout(t, widths, u, cell_mar_cm=0.08)
    _par(doc, "* «Медосмотры» — 14 строк Приложения № 2 (все позиции, где в графе стоит "
              "[до подписания: пункт приказа 29н]).", size=8, italic=True,
         space_before=4, space_after=8)

    _par(doc, "Дополнительно проверить до подписания (пометок в письме нет):",
         bold=True, size=10, space_before=4, space_after=3)
    _par(doc, "— полноту перечня Приложения № 2 (25 работников) со штатным расписанием "
              "(ШР-2026: 44 штатные единицы): по ШР заняты также грузчики (в ШР — 6, в "
              "списке СОУТ — 1: Бозоров С.З.), менеджеры продаж (2 шт., удаленная работа) "
              "и диспетчер (1 шт., удаленная работа). Если эти работники включаются в "
              "СОУТ — дополнить Приложение № 2 строками (рабочее место, обязанности, "
              "доли времени);", size=10, space_after=2)
    _par(doc, "— персональные данные 25 работников (Ф.И.О., СНИЛС) — по кадровым "
              "документам, до подписания экземпляра.", size=10, space_after=8)

    _par(doc, "Чек-лист заполнен и утверждаю:", size=10, space_after=14)
    _par(doc, "____________________ / ________________________ / 2026 г.", size=10,
         space_after=1)
    _par(doc, "            (подпись)            (Ф.И.О., должность)                 (дата)",
         size=8, italic=True)

    doc.save(OUT)
    print("Сохранено:", OUT)

    # самопроверка
    d2 = Document(OUT)
    alltext = "\n".join(p.text for p in d2.paragraphs)
    for tb in d2.tables:
        for r in tb.rows:
            for c in r.cells:
                alltext += "\n" + c.text
    for probe, expect in (("[до подписания]", 3), ("[уточнить]", 0)):
        n = alltext.count(probe)
        print(f"  '{probe}': {n}" + ("  OK" if (n == expect if expect else n == 0) else "  <-- ПРОВЕРИТЬ"))
    print(f"  строк таблицы: {len(d2.tables[0].rows)} (1 заголовок + {len(ROWS)})")


if __name__ == "__main__":
    build()
